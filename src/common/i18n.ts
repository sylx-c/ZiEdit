const DICTS: Record<Lang, Record<string, string>> = { 'zh-CN': ZH_CN, 'en-US': EN_US };

/** 字典只读视图（i18n 一致性测试用：key 对齐 / 占位符一致 / 双向引用核对） */
export function dict(lang: Lang): Record<string, string> {
  return DICTS[lang] ?? {};
}

let current: Lang = 'zh-CN';

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (saved === 'zh-CN' || saved === 'en-US') return saved;
  } catch {
    /* 非浏览器环境 */
  }
  const nav = typeof navigator !== 'undefined' ? navigator.language : '';
  return nav && nav.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US';
}

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  if (current === lang) return;
  current = lang;
  try {
    localStorage.setItem(STORE_KEY, lang);
  } catch {
    /* 忽略持久化失败 */
  }
  window.dispatchEvent(new CustomEvent('i18n-change', { detail: lang }));
}

/** 取当前语言文案；缺 key 回退中文，再缺返回 key 本身 */
export function t(key: string): string {
  return DICTS[current]?.[key] ?? DICTS['zh-CN'][key] ?? key;
}

// 错误码表（H-4 正式感外壳）：err.* 文案注入稳定代码前缀，便于对照文档排障。
// 分段：E1xxx 文件读写、E2xxx 编辑保存、E3xxx 查找替换、E4xxx 格式化、E5xxx 对话框/其他
const ERR_CODES: Record<string, string> = {
  'err.openFail': 'E1001',
  'err.readFail': 'E1002',
  'err.saveFail': 'E1003',
  'err.saveAsFail': 'E1004',
  'err.createFail': 'E1005',
  'err.renameFail': 'E1006',
  'err.trashFail': 'E1007',
  'err.nlSaveFail': 'E1008',
  'err.openUrlFail': 'E1009',
  'err.openLogDirFail': 'E1010',
  'err.findFail': 'E3001',
  'err.formatFail': 'E4001',
  'err.missingEl': 'E5001',
};

/** 取文案并插值：{0}/{1}… 依次替换为传入参数（便于英文语序调整）；
 *  err.* 键自动带错误码前缀「[E1003] 保存失败：…」（无码的 err 键不加前缀） */
export function tf(key: string, ...args: (string | number)[]): string {
  const text = t(key).replace(/\{(\d+)\}/g, (_m, i: string) => String(args[Number(i)] ?? ''));
  const code = ERR_CODES[key];
  return code ? `[${code}] ${text}` : text;
}

/** 初始化（启动时调用一次） */
export function initI18n(): Lang {
  current = detectLang();
  return current;
}

/** 启动重同步（P3-30 语言真相源）：settings.language 为唯一真相，localStorage 仅是启动早期的
 *  探测缓存（settingsLoad 是 IPC，异步晚于首次绘制）。设置与缓存不一致时（外部改过 settings.json、
 *  换机迁移、旧版本残留）以设置为准就地切换并回写缓存。
 *  返回 true 表示已切换，调用方须重建已挂载的界面文案（chrome/侧栏）。 */
export function syncLangFromSettings(lang?: string): boolean {
  if (lang !== 'zh-CN' && lang !== 'en-US') return false; // 未显式设置：保持系统/缓存探测结果
  if (lang === current) return false;
  setLang(lang); // 内部回写 localStorage 缓存，兼容旧数据读取路径
  return true;
}

/** 语言变化订阅（视图重渲染用） */
export function onLangChange(handler: (lang: Lang) => void): () => void {
  const listener = (e: Event) => handler((e as CustomEvent<Lang>).detail);
  window.addEventListener('i18n-change', listener);
  return () => window.removeEventListener('i18n-change', listener);
}
